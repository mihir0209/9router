import { describe, expect, it } from "vitest";
import {
  buildCreateIndexSqlPostgres,
  buildCreateTableSqlPostgres,
  buildPostgresSchemaStatements,
  pgIdent,
} from "../../src/lib/db/adapters/postgresSchema.js";
import { TABLES } from "../../src/lib/db/schema.js";

// The Postgres port is verified against a real PostgreSQL 17 as well, but these
// assertions pin the three dialect traps that would otherwise only surface as a
// runtime failure on a fresh database — and a fresh database is exactly what
// nobody has when a deploy fails.

describe("postgres schema", () => {
  it("quotes every identifier, because unquoted camelCase folds to lowercase", () => {
    const sql = buildCreateTableSqlPostgres("providerConnections", TABLES.providerConnections);
    expect(sql).toContain('"providerConnections"');
    expect(sql).toContain('"isActive"');
    // A bare camelCase identifier would become "isactive" in Postgres, so
    // stripping the quoted ones must leave no camelCase behind.
    const unquoted = sql.replace(/"[^"]*"/g, "");
    expect(unquoted).not.toMatch(/isActive/);
  });

  it("maps REAL to DOUBLE PRECISION, not float4", () => {
    // SQLite REAL is an 8-byte float; Postgres REAL is 4 bytes. Leaving REAL
    // would round cost and budgetUsd to ~7 significant digits — and this is
    // money.
    const sql = buildCreateTableSqlPostgres("apiKeys", TABLES.apiKeys);
    expect(sql).toContain('"budgetUsd" DOUBLE PRECISION');
    expect(sql).not.toMatch(/"budgetUsd" REAL/);
  });

  it("translates AUTOINCREMENT to an identity column", () => {
    const sql = buildCreateTableSqlPostgres("usageHistory", TABLES.usageHistory);
    expect(sql).toMatch(/"id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/);
    expect(sql).not.toMatch(/AUTOINCREMENT/);
  });

  it("keeps the settings singleton constraint", () => {
    const sql = buildCreateTableSqlPostgres("settings", TABLES.settings);
    expect(sql).toContain("CHECK (id = 1)");
  });

  it("quotes index columns and preserves DESC", () => {
    const sql = buildCreateIndexSqlPostgres(
      "CREATE INDEX IF NOT EXISTS idx_uh_ts ON usageHistory(timestamp DESC)"
    );
    expect(sql).toBe(
      'CREATE INDEX IF NOT EXISTS idx_uh_ts ON "usageHistory" ("timestamp" DESC)'
    );
  });

  it("quotes multiple index columns", () => {
    const sql = buildCreateIndexSqlPostgres(
      "CREATE INDEX IF NOT EXISTS idx_pc_provider_active ON providerConnections(provider, isActive)"
    );
    expect(sql).toContain('("provider", "isActive")');
  });

  it("escapes embedded quotes in identifiers", () => {
    expect(pgIdent('we"ird')).toBe('"we""ird"');
  });

  it("emits one create per table plus every index", () => {
    const statements = buildPostgresSchemaStatements();
    const tables = Object.keys(TABLES);
    for (const table of tables) {
      expect(statements.some((s) => s.startsWith(`CREATE TABLE IF NOT EXISTS "${table}"`))).toBe(true);
    }
    const indexCount = tables.reduce((n, t) => n + (TABLES[t].indexes || []).length, 0);
    expect(statements.filter((s) => s.startsWith("CREATE INDEX")).length).toBe(indexCount);
  });

  it("emits no SQLite-only syntax anywhere", () => {
    for (const statement of buildPostgresSchemaStatements()) {
      expect(statement).not.toMatch(/\bPRAGMA\b/i);
      expect(statement).not.toMatch(/AUTOINCREMENT/i);
      expect(statement).not.toMatch(/\bREAL\b/);
    }
  });
});
