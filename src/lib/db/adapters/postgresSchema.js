// Postgres rendering of the schema in schema.js.
//
// The column set is deliberately NOT re-specified here. Postgres gets the same
// logical columns with the same logical types as SQLite (TEXT / INTEGER / REAL),
// for one reason: the in-memory engine in memoryEngine.js serves every read and
// write before anything reaches the database, so a row must mean exactly the
// same thing in both engines. Diverging types would mean a conversion layer and
// a class of bug where SQLite and Postgres disagree about a value.
//
// Two things genuinely have to change:
//
//   REAL -> DOUBLE PRECISION. SQLite's REAL is an 8-byte float; Postgres's REAL
//   is a 4-byte float. Keeping REAL here would quietly round `cost` and
//   `budgetUsd` to ~7 significant digits — and this is money.
//
//   INTEGER PRIMARY KEY AUTOINCREMENT -> GENERATED BY DEFAULT AS IDENTITY.
//   SQLite spells it AUTOINCREMENT; Postgres spells it an identity column.
//   "BY DEFAULT" (not ALWAYS) because the engine assigns ids in-process for
//   usageHistory, and a bare INSERT that omits the id must still work.
//
// Everything else in the schema is already valid Postgres: TEXT PRIMARY KEY,
// TEXT UNIQUE NOT NULL, CREATE INDEX IF NOT EXISTS (9.5+), and the settings
// singleton's INTEGER PRIMARY KEY CHECK (id = 1).
//
// Identifiers are quoted everywhere. Postgres folds unquoted identifiers to
// lower case, and this schema is camelCase throughout (providerConnections,
// apiKeyId, connectionId) — unquoted it would silently create a table called
// "providerconnections" that nothing ever reads.

import { TABLES } from "../schema.js";

/** Tables whose integer key the database generates when one is not supplied. */
const IDENTITY_TABLES = new Set(["usageHistory"]);

/** Quote an identifier for Postgres (camelCase would otherwise be folded). */
export function pgIdent(name) {
  return `"${String(name).replace(/"/g, '""')}"`;
}

/** SQLite type text -> Postgres type text. */
function pgColumnType(sqliteType) {
  if (/^REAL\b/i.test(sqliteType.trim())) return "DOUBLE PRECISION";
  if (/^INTEGER PRIMARY KEY AUTOINCREMENT$/i.test(sqliteType.trim())) return "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";
  return sqliteType.trim();
}

/** One table definition, as it should be created in Postgres. */
export function buildCreateTableSqlPostgres(name, def) {
  const columns = [];
  for (const [column, type] of Object.entries(def.columns)) {
    if (IDENTITY_TABLES.has(name) && /AUTOINCREMENT$/i.test(type)) {
      // The identity clause already carries PRIMARY KEY.
      columns.push(`${pgIdent(column)} ${pgColumnType(type)}`);
      continue;
    }
    columns.push(`${pgIdent(column)} ${pgColumnType(type)}`);
  }
  if (def.primaryKey) columns.push(def.primaryKey);
  return `CREATE TABLE IF NOT EXISTS ${pgIdent(name)} (${columns.join(", ")})`;
}

/**
 * Index DDL with the table and every column quoted.
 *
 * Quoting the table is not enough: "ON providerConnections(provider, isActive)"
 * folds isActive to isactive and the statement fails. Each column is quoted
 * individually while preserving any ASC/DESC modifier, so
 * "timestamp DESC" becomes "\"timestamp\" DESC".
 */
export function buildCreateIndexSqlPostgres(statement) {
  return statement.replace(
    /\bON\s+(\w+)\s*\(([^)]*)\)/i,
    (_m, table, columns) => {
      const quoted = splitIndexColumns(columns)
        .map((part) => {
          const m = part.trim().match(/^(\w+)(\s+(?:ASC|DESC))?$/i);
          if (!m) return part.trim();
          // m[2] carries its own leading whitespace, so trim before joining or
          // the rendered SQL gets a double space.
          return m[2] ? `${pgIdent(m[1])} ${m[2].trim().toUpperCase()}` : pgIdent(m[1]);
        })
        .join(", ");
      return `ON ${pgIdent(table)} (${quoted})`;
    }
  );
}

/** Split "a, b DESC" on commas that are not inside parentheses. */
function splitIndexColumns(input) {
  const out = [];
  let depth = 0;
  let current = "";
  for (const ch of input) {
    if (ch === "(") depth++;
    if (ch === ")") depth--;
    if (ch === "," && depth === 0) {
      out.push(current);
      current = "";
      continue;
    }
    current += ch;
  }
  if (current.trim()) out.push(current);
  return out;
}

/** Every statement needed to bring an empty Postgres up to the current schema. */
export function buildPostgresSchemaStatements() {
  const statements = [];
  for (const [name, def] of Object.entries(TABLES)) {
    statements.push(buildCreateTableSqlPostgres(name, def));
    for (const index of def.indexes || []) statements.push(buildCreateIndexSqlPostgres(index));
  }
  return statements;
}

export { TABLES };
